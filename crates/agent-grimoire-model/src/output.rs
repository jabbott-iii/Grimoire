//! Clients, anchors and the per-client output map of a manifest (`architecture.md` §6.1, §8.3).

use std::borrow::Cow;
use std::fmt;
use std::str::FromStr;

use schemars::{JsonSchema, Schema, SchemaGenerator, json_schema};
use serde::{Deserialize, Serialize};

use crate::{InvalidValue, Kind, RelPath};

/// A client Grimoire renders for (ADR-0005).
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize, JsonSchema,
)]
#[serde(rename_all = "kebab-case")]
pub enum ClientId {
    /// Claude Code.
    ClaudeCode,
    /// The portable target: `AGENTS.md` plus `.agents/skills/`.
    AgentsMd,
    /// The Codex CLI.
    Codex,
    /// Cursor.
    Cursor,
    /// Gemini CLI.
    GeminiCli,
    /// GitHub Copilot.
    Copilot,
}

impl ClientId {
    /// Every client, in ADR-0005 order.
    pub const ALL: [ClientId; 6] = [
        ClientId::ClaudeCode,
        ClientId::AgentsMd,
        ClientId::Codex,
        ClientId::Cursor,
        ClientId::GeminiCli,
        ClientId::Copilot,
    ];

    /// The identifier used in manifests and `grimoire.toml`.
    #[must_use]
    pub fn as_str(self) -> &'static str {
        match self {
            ClientId::ClaudeCode => "claude-code",
            ClientId::AgentsMd => "agents-md",
            ClientId::Codex => "codex",
            ClientId::Cursor => "cursor",
            ClientId::GeminiCli => "gemini-cli",
            ClientId::Copilot => "copilot",
        }
    }

    /// Whether this client has a destination for `anchor` (`architecture.md` §8.3).
    ///
    /// Hooks are Claude Code only, and Codex has no agents: no other client can
    /// keep a failed hook from letting the action through, and a Codex agent
    /// can't be restricted to its declared tools (ADR-0008).
    #[must_use]
    pub fn supports(self, anchor: Anchor) -> bool {
        use Anchor::{Agents, Hooks, Instructions, Mcp, Rules, Skills};
        match self {
            ClientId::ClaudeCode => matches!(anchor, Rules | Skills | Agents | Mcp | Hooks),
            ClientId::AgentsMd => matches!(anchor, Instructions | Skills),
            ClientId::Codex => matches!(anchor, Instructions | Skills | Mcp),
            ClientId::Cursor | ClientId::Copilot => matches!(anchor, Rules | Skills | Agents | Mcp),
            ClientId::GeminiCli => matches!(anchor, Instructions | Skills | Agents | Mcp),
        }
    }
}

impl fmt::Display for ClientId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.as_str())
    }
}

/// A client-neutral destination class. Each adapter resolves anchors to paths.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum Anchor {
    /// Per-rule instruction files, e.g. `.claude/rules/`.
    Rules,
    /// Skill directories, e.g. `.claude/skills/` or `.agents/skills/`.
    Skills,
    /// Subagent definition files.
    Agents,
    /// The client's shared instruction file, e.g. `AGENTS.md` or `GEMINI.md`.
    Instructions,
    /// The client's MCP configuration file.
    Mcp,
    /// The client's hook configuration.
    Hooks,
}

impl Anchor {
    /// Every anchor.
    pub const ALL: [Anchor; 6] = [
        Anchor::Rules,
        Anchor::Skills,
        Anchor::Agents,
        Anchor::Instructions,
        Anchor::Mcp,
        Anchor::Hooks,
    ];

    /// The anchor's name in a destination string.
    #[must_use]
    pub fn as_str(self) -> &'static str {
        match self {
            Anchor::Rules => "rules",
            Anchor::Skills => "skills",
            Anchor::Agents => "agents",
            Anchor::Instructions => "instructions",
            Anchor::Mcp => "mcp",
            Anchor::Hooks => "hooks",
        }
    }

    /// Whether destinations under this anchor name a file or directory
    /// (`rules:x.md`) rather than a single shared file (`instructions`).
    #[must_use]
    pub fn takes_path(self) -> bool {
        matches!(self, Anchor::Rules | Anchor::Skills | Anchor::Agents)
    }

    /// Whether an asset of `kind` may target this anchor.
    #[must_use]
    pub fn accepts_kind(self, kind: Kind) -> bool {
        match self {
            Anchor::Rules | Anchor::Instructions => kind == Kind::Rule,
            Anchor::Skills => kind == Kind::Skill,
            Anchor::Agents => kind == Kind::Agent,
            Anchor::Mcp => kind == Kind::McpServer,
            Anchor::Hooks => kind == Kind::Tool,
        }
    }
}

impl fmt::Display for Anchor {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.as_str())
    }
}

/// How an output is written (`architecture.md` §6.1, §7.2).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "kebab-case")]
pub enum Strategy {
    /// A whole file (or directory tree), byte-for-byte.
    Copy,
    /// A whole file generated by the adapter, e.g. with client frontmatter.
    Render,
    /// A managed block in a shared Markdown file.
    Block,
    /// An owned entry in a JSON or TOML config file.
    Entry,
}

impl Strategy {
    /// Whether this strategy can write to `anchor`.
    #[must_use]
    pub fn allows(self, anchor: Anchor) -> bool {
        match self {
            Strategy::Copy => anchor == Anchor::Skills,
            Strategy::Render => matches!(anchor, Anchor::Rules | Anchor::Agents),
            Strategy::Block => anchor == Anchor::Instructions,
            Strategy::Entry => matches!(anchor, Anchor::Mcp | Anchor::Hooks),
        }
    }

    /// Whether outputs with this strategy read a source file.
    #[must_use]
    pub fn needs_src(self) -> bool {
        self != Strategy::Entry
    }
}

/// An output destination: an anchor, plus a relative path for anchors that take one.
///
/// Written `rules:rust-errors.md`, `skills:my-skill/SKILL.md`, `instructions`, `mcp` or `hooks`.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(try_from = "String", into = "String")]
pub struct Destination {
    anchor: Anchor,
    path: Option<RelPath>,
}

impl Destination {
    /// Parses a destination string.
    ///
    /// # Errors
    ///
    /// Fails for an unknown anchor, a missing path on an anchor that needs one,
    /// a path on an anchor that takes none, or an unsafe path.
    pub fn parse(value: &str) -> Result<Self, InvalidValue> {
        let (name, path) = match value.split_once(':') {
            Some((name, path)) => (name, Some(path)),
            None => (value, None),
        };
        let anchor = Anchor::ALL
            .into_iter()
            .find(|a| a.as_str() == name)
            .ok_or_else(|| {
                InvalidValue::new(
                    "destination",
                    value,
                    "the anchor must be one of rules, skills, agents, instructions, mcp, hooks",
                )
            })?;
        let path = match (anchor.takes_path(), path) {
            (true, Some(path)) => Some(
                RelPath::new(path)
                    .map_err(|e| InvalidValue::new("destination", value, e.reason().to_owned()))?,
            ),
            (true, None) => {
                return Err(InvalidValue::new(
                    "destination",
                    value,
                    format!("the `{anchor}` anchor needs a path, e.g. `{anchor}:<id>.md`"),
                ));
            }
            (false, Some(_)) => {
                return Err(InvalidValue::new(
                    "destination",
                    value,
                    format!("the `{anchor}` anchor names a single shared file and takes no path"),
                ));
            }
            (false, None) => None,
        };
        Ok(Self { anchor, path })
    }

    /// The anchor.
    #[must_use]
    pub fn anchor(&self) -> Anchor {
        self.anchor
    }

    /// The path under the anchor, for anchors that take one.
    #[must_use]
    pub fn path(&self) -> Option<&RelPath> {
        self.path.as_ref()
    }
}

impl fmt::Display for Destination {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match &self.path {
            Some(path) => write!(f, "{}:{path}", self.anchor),
            None => write!(f, "{}", self.anchor),
        }
    }
}

impl TryFrom<String> for Destination {
    type Error = InvalidValue;

    fn try_from(value: String) -> Result<Self, Self::Error> {
        Self::parse(&value)
    }
}

impl From<Destination> for String {
    fn from(value: Destination) -> Self {
        value.to_string()
    }
}

impl FromStr for Destination {
    type Err = InvalidValue;

    fn from_str(value: &str) -> Result<Self, Self::Err> {
        Self::parse(value)
    }
}

impl JsonSchema for Destination {
    fn schema_name() -> Cow<'static, str> {
        "Destination".into()
    }

    fn json_schema(_: &mut SchemaGenerator) -> Schema {
        json_schema!({
            "type": "string",
            "pattern": "^((rules|skills|agents):.+|instructions|mcp|hooks)$",
            "description": "An anchor resolved by each client adapter: \"rules:<path>\", \"skills:<path>\", \"agents:<path>\", \"instructions\", \"mcp\" or \"hooks\"."
        })
    }
}

/// One output of an asset for one client.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields, rename_all = "kebab-case")]
pub struct OutputSpec {
    /// Source file or directory, relative to the asset directory. Omitted for `entry` outputs.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub src: Option<RelPath>,
    /// Where the output goes, as an anchor the client adapter resolves.
    pub to: Destination,
    /// How the output is written.
    pub strategy: Strategy,
}

/// The outputs of an asset for one client. Presence of the table means the client is supported.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields, rename_all = "kebab-case")]
pub struct ClientOutputs {
    /// The outputs, in order.
    #[serde(default)]
    pub outputs: Vec<OutputSpec>,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn destinations_parse() {
        let d = Destination::parse("rules:rust-errors.md").unwrap();
        assert_eq!(d.anchor(), Anchor::Rules);
        assert_eq!(d.path().unwrap().as_str(), "rust-errors.md");
        assert_eq!(d.to_string(), "rules:rust-errors.md");
        assert!(Destination::parse("instructions").unwrap().path().is_none());
        assert!(Destination::parse("rules").is_err());
        assert!(Destination::parse("mcp:x.json").is_err());
        assert!(Destination::parse("rules:../escape.md").is_err());
        assert!(Destination::parse("unknown:x").is_err());
        assert!(Destination::parse("skills:my-skill/SKILL.md").is_ok());
    }

    #[test]
    fn strategy_anchor_matrix() {
        assert!(Strategy::Copy.allows(Anchor::Skills));
        assert!(!Strategy::Copy.allows(Anchor::Rules));
        assert!(Strategy::Render.allows(Anchor::Agents));
        assert!(Strategy::Block.allows(Anchor::Instructions));
        assert!(Strategy::Entry.allows(Anchor::Mcp));
        assert!(!Strategy::Entry.needs_src());
    }

    #[test]
    fn portable_target_has_no_agents_or_mcp() {
        assert!(!ClientId::AgentsMd.supports(Anchor::Agents));
        assert!(!ClientId::AgentsMd.supports(Anchor::Mcp));
        assert!(ClientId::AgentsMd.supports(Anchor::Instructions));
        assert!(ClientId::ClaudeCode.supports(Anchor::Rules));
        assert!(!ClientId::ClaudeCode.supports(Anchor::Instructions));
    }
}
