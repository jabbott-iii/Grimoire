//! The user's project: `grimoire.toml`, `grimoire.lock`, and edits to the config.
//!
//! Both files are read and written through the confined [`Root`], so a symlinked
//! `grimoire.toml` is refused like any other managed path.

use std::collections::BTreeSet;
use std::path::PathBuf;

use agent_grimoire_install::fs::{FsError, Root};
use agent_grimoire_model::{
    AssetId, ClientId, Diagnostic, Lockfile, Permission, ProjectConfig, RelPath, Unit, has_errors,
    validate,
};
use toml_edit::{Array, DocumentMut, InlineTable, Item, Table, TableLike, Value};

use crate::out::{Exit, Out};

pub(crate) const CONFIG: &str = "grimoire.toml";
pub(crate) const LOCK: &str = "grimoire.lock";
const LOCK_HEADER: &str = "# Generated by grimoire. Do not edit by hand.\n";

/// An opened project root.
pub(crate) struct Project {
    pub(crate) dir: PathBuf,
    pub(crate) root: Root,
}

pub(crate) fn rel(path: &str) -> RelPath {
    RelPath::new(path).unwrap_or_else(|_| unreachable!("`{path}` is a valid path"))
}

/// Maps a filesystem error to a diagnostic and exit status.
pub(crate) fn fs_exit(out: &mut Out<'_, '_>, e: &FsError) -> Exit {
    match e {
        FsError::Refused { .. } => out.fail(Exit::Refused, "fs/refused", e.to_string()),
        FsError::InTheWay { .. } => out.fail(Exit::Conflict, "fs/in-the-way", e.to_string()),
        FsError::Io { .. } => out.fail(Exit::Failure, "fs/io", e.to_string()),
    }
}

impl Project {
    /// Opens the project root: `-C DIR` or the current directory.
    pub(crate) fn open(out: &mut Out<'_, '_>, directory: Option<&PathBuf>) -> Result<Self, Exit> {
        let dir = match directory {
            Some(d) if d.is_absolute() => d.clone(),
            Some(d) => out.ctx.cwd.join(d),
            None => out.ctx.cwd.clone(),
        };
        match Root::open(&dir) {
            Ok(root) => Ok(Self { dir, root }),
            Err(e) => Err(fs_exit(out, &e)),
        }
    }

    pub(crate) fn read(&self, out: &mut Out<'_, '_>, path: &str) -> Result<Option<String>, Exit> {
        match self.root.read(&rel(path)) {
            Ok(None) => Ok(None),
            Ok(Some(bytes)) => match String::from_utf8(bytes) {
                Ok(text) => Ok(Some(text)),
                Err(_) => Err(out.fail(
                    Exit::Invalid,
                    "project/encoding",
                    format!("{path} is not UTF-8"),
                )),
            },
            Err(e) => Err(fs_exit(out, &e)),
        }
    }

    pub(crate) fn write(&self, out: &mut Out<'_, '_>, path: &str, text: &str) -> Result<(), Exit> {
        self.root
            .write(&rel(path), text.as_bytes())
            .map_err(|e| fs_exit(out, &e))
    }

    pub(crate) fn remove(&self, out: &mut Out<'_, '_>, path: &str) -> Result<(), Exit> {
        self.root.remove(&rel(path)).map_err(|e| fs_exit(out, &e))
    }

    /// Whether a regular file is at `path`, checked as reading or removing it
    /// would be, without reading it.
    pub(crate) fn has_file(&self, out: &mut Out<'_, '_>, path: &str) -> Result<bool, Exit> {
        self.root.has_file(&rel(path)).map_err(|e| fs_exit(out, &e))
    }

    /// Whether anything is at `path`, through the root and without following a
    /// symbolic link. A link at `path` itself counts, even a broken one; a name
    /// inside a linked directory doesn't. Every error counts as absent, including
    /// a file or an unreadable directory on the way: the answer only guides
    /// detection and warnings, and reads no content.
    pub(crate) fn exists(&self, path: &str) -> bool {
        matches!(self.root.exists(&rel(path)), Ok(true))
    }

    /// Reads and validates `grimoire.toml`, returning it with its text.
    pub(crate) fn config(&self, out: &mut Out<'_, '_>) -> Result<(ProjectConfig, String), Exit> {
        let Some(text) = self.read(out, CONFIG)? else {
            return Err(out.fail(
                Exit::Invalid,
                "project/no-config",
                format!("no {CONFIG} in {}; run `grimoire init`", self.dir.display()),
            ));
        };
        let config = parse_config(out, &text)?;
        Ok((config, text))
    }

    /// Reads and validates `grimoire.lock`. Absent means an empty lock.
    pub(crate) fn lock(&self, out: &mut Out<'_, '_>) -> Result<(Lockfile, Option<String>), Exit> {
        let Some(text) = self.read(out, LOCK)? else {
            return Ok((Lockfile::new(), None));
        };
        let lock = match Lockfile::from_toml(&text) {
            Ok(lock) => lock,
            Err(e) => {
                return Err(out.fail(Exit::Invalid, "project/lock-parse", format!("{LOCK}: {e}")));
            }
        };
        let mut problems: Vec<Diagnostic> = validate::lockfile(&lock)
            .into_iter()
            .map(|d| d.in_file(LOCK))
            .collect();
        // Grimoire only ever writes where an adapter puts content, and only the
        // unit an adapter owns there, so a lock that names anything else
        // (`.git/HEAD`, `.env`, a whole `.codex/config.toml`, …) was not written by it.
        let asset_outputs = lock.assets.iter().flat_map(|a| &a.outputs);
        for o in asset_outputs {
            let problem = match agent_grimoire_adapters::managed_unit(&o.path) {
                None => format!("`{}` is not a location grimoire manages", o.path),
                Some(unit) if unit != o.unit => format!(
                    "grimoire owns only {} at `{}`, not {}",
                    unit_name(unit),
                    o.path,
                    unit_name(o.unit)
                ),
                Some(_) => continue,
            };
            problems.push(
                Diagnostic::error(
                    "project/lock-path",
                    format!("{problem}; grimoire.lock may have been edited by hand"),
                )
                .in_file(LOCK),
            );
        }
        for o in lock.outputs.iter().filter(|o| {
            !agent_grimoire_adapters::is_project_location(&o.path) || o.unit != Unit::Block
        }) {
            problems.push(
                Diagnostic::error(
                    "project/lock-path",
                    format!("`{}` is not a location grimoire manages for itself; grimoire.lock may have been edited by hand", o.path),
                )
                .in_file(LOCK),
            );
        }
        if has_errors(&problems) {
            out.diags(problems);
            return Err(Exit::Invalid);
        }
        Ok((lock, Some(text)))
    }

    /// Writes `lock` if it differs from what is on disk. Returns whether it wrote.
    pub(crate) fn write_lock(
        &self,
        out: &mut Out<'_, '_>,
        lock: &Lockfile,
        old: Option<&str>,
    ) -> Result<bool, Exit> {
        let text = render_lock(out, lock)?;
        if !lock_differs(old, &text) {
            return Ok(false);
        }
        self.write(out, LOCK, &text)?;
        Ok(true)
    }
}

/// Whether `text`, a rendered lock, differs from `old`, the lock on disk (`None`
/// when there is none). A missing lock always differs: the first `apply`
/// creates one even when it records nothing, so `verify` has a lock to check.
pub(crate) fn lock_differs(old: Option<&str>, text: &str) -> bool {
    // A checkout that converted line endings is still the same lock.
    old.map(|o| o.replace("\r\n", "\n")).as_deref() != Some(text)
}

/// The lock as stored on disk.
pub(crate) fn render_lock(out: &mut Out<'_, '_>, lock: &Lockfile) -> Result<String, Exit> {
    let mut lock = lock.clone();
    lock.canonicalize();
    match toml::to_string(&lock) {
        Ok(body) => Ok(format!("{LOCK_HEADER}{body}")),
        Err(e) => Err(out.fail(
            Exit::Failure,
            "project/lock-write",
            format!("cannot serialize {LOCK}: {e}"),
        )),
    }
}

pub(crate) fn parse_config(out: &mut Out<'_, '_>, text: &str) -> Result<ProjectConfig, Exit> {
    let config = match ProjectConfig::from_toml(text) {
        Ok(config) => config,
        Err(e) => {
            return Err(out.fail(
                Exit::Invalid,
                "project/config-parse",
                format!("{CONFIG}: {e}"),
            ));
        }
    };
    let problems: Vec<Diagnostic> = validate::project_config(&config)
        .into_iter()
        .map(|d| d.in_file(CONFIG))
        .collect();
    let failed = has_errors(&problems);
    out.diags(problems);
    if failed {
        return Err(Exit::Invalid);
    }
    Ok(config)
}

/// A new `grimoire.toml`.
pub(crate) fn new_config(clients: &[ClientId]) -> String {
    let clients: Vec<String> = clients.iter().map(|c| format!("\"{c}\"")).collect();
    format!(
        "# Grimoire project configuration. `grimoire add` and `grimoire remove` edit it,\n\
         # and you can too; `grimoire apply` makes the project match it.\n\
         format = 1\n\
         clients = [{}]\n\
         \n\
         [assets]\n",
        clients.join(", ")
    )
}

/// Comment-preserving edits to `grimoire.toml`.
pub(crate) struct ConfigEdit {
    doc: DocumentMut,
}

fn string_array<'a>(values: impl IntoIterator<Item = &'a str>) -> Array {
    let mut array = Array::new();
    for v in values {
        array.push(v);
    }
    array
}

fn permissions_array(perms: &BTreeSet<Permission>) -> Array {
    let names: Vec<String> = perms.iter().map(ToString::to_string).collect();
    string_array(names.iter().map(String::as_str))
}

impl ConfigEdit {
    pub(crate) fn parse(text: &str) -> Result<Self, String> {
        text.parse::<DocumentMut>()
            .map(|doc| Self { doc })
            .map_err(|e| e.to_string())
    }

    pub(crate) fn render(&self) -> String {
        self.doc.to_string()
    }

    /// The table `name`, created if missing. Both `[name]` tables and inline
    /// `name = { … }` tables are edited in place.
    fn table(&mut self, name: &str) -> Option<&mut dyn TableLike> {
        let item = self.doc.entry(name).or_insert_with(|| {
            let mut t = Table::new();
            t.set_implicit(false);
            Item::Table(t)
        });
        item.as_table_like_mut()
    }

    /// Adds `id = "<req>"` under `[assets]` unless it is already there.
    pub(crate) fn add_asset(&mut self, id: &AssetId, req: &str) -> bool {
        let Some(assets) = self.table("assets") else {
            return false;
        };
        if assets.contains_key(id.as_str()) {
            return false;
        }
        assets.insert(id.as_str(), toml_edit::value(req));
        true
    }

    /// Sets the `allow` list of an `[assets]` entry, turning `id = "^1"` into an inline table.
    pub(crate) fn set_inline_allow(&mut self, id: &AssetId, perms: &BTreeSet<Permission>) {
        let Some(assets) = self.table("assets") else {
            return;
        };
        let Some(item) = assets.get_mut(id.as_str()) else {
            return;
        };
        if let Some(req) = item.as_str().map(str::to_owned) {
            let mut inline = InlineTable::new();
            inline.insert("version", Value::from(req));
            // Keep a trailing comment on the line, which lives in the value's decor.
            if let Some(decor) = item.as_value().map(|v| v.decor().clone()) {
                *inline.decor_mut() = decor;
            }
            *item = toml_edit::value(inline);
        }
        if let Some(inline) = item.as_inline_table_mut() {
            inline.insert("allow", Value::Array(permissions_array(perms)));
        } else if let Some(table) = item.as_table_mut() {
            table.insert("allow", toml_edit::value(permissions_array(perms)));
        }
    }

    /// Sets `[allow] id = [...]`.
    pub(crate) fn set_allow(&mut self, id: &AssetId, perms: &BTreeSet<Permission>) {
        if let Some(allow) = self.table("allow") {
            allow.insert(id.as_str(), toml_edit::value(permissions_array(perms)));
        }
    }

    /// Appends `value` to the top-level array `key` unless present.
    pub(crate) fn add_to_array(&mut self, key: &str, value: &str) -> bool {
        let item = self
            .doc
            .entry(key)
            .or_insert_with(|| toml_edit::value(Array::new()));
        let Some(array) = item.as_array_mut() else {
            return false;
        };
        if array.iter().any(|v| v.as_str() == Some(value)) {
            return false;
        }
        array.push(value);
        true
    }

    pub(crate) fn remove_asset(&mut self, id: &AssetId) -> bool {
        self.doc
            .get_mut("assets")
            .and_then(Item::as_table_like_mut)
            .and_then(|t| t.remove(id.as_str()))
            .is_some()
    }

    pub(crate) fn remove_allow(&mut self, id: &AssetId) -> bool {
        let removed = self
            .doc
            .get_mut("allow")
            .and_then(Item::as_table_like_mut)
            .and_then(|t| t.remove(id.as_str()))
            .is_some();
        if self
            .doc
            .get("allow")
            .and_then(Item::as_table_like)
            .is_some_and(TableLike::is_empty)
        {
            self.doc.remove("allow");
        }
        removed
    }

    pub(crate) fn remove_from_array(&mut self, key: &str, value: &str) -> bool {
        let Some(array) = self.doc.get_mut(key).and_then(Item::as_array_mut) else {
            return false;
        };
        let before = array.len();
        array.retain(|v| v.as_str() != Some(value));
        before != array.len()
    }
}

/// A unit as the lock writes it, with its article.
fn unit_name(unit: Unit) -> &'static str {
    match unit {
        Unit::File => "a `file`",
        Unit::Block => "a `block`",
        Unit::Entry => "an `entry`",
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_missing_lock_differs_and_line_endings_dont() {
        let text = "# Generated by grimoire. Do not edit by hand.\nformat = 1\n";
        assert!(lock_differs(None, text));
        assert!(!lock_differs(Some(text), text));
        assert!(!lock_differs(Some(&text.replace('\n', "\r\n")), text));
        assert!(lock_differs(Some("format = 1\n"), text));
    }

    #[test]
    fn inline_tables_and_trailing_comments() {
        let text = "format = 1\nclients = [\"claude-code\"]\nassets = { old = \"^1\" }\n";
        let mut edit = ConfigEdit::parse(text).unwrap();
        let id = AssetId::new("new-one").unwrap();
        assert!(edit.add_asset(&id, "^2"));
        assert!(
            ProjectConfig::from_toml(&edit.render())
                .unwrap()
                .assets
                .contains_key(&id)
        );

        let text =
            "format = 1\nclients = [\"claude-code\"]\n[assets]\nold = \"^1\"  # waiting on 2.0\n";
        let mut edit = ConfigEdit::parse(text).unwrap();
        edit.set_inline_allow(
            &AssetId::new("old").unwrap(),
            &BTreeSet::from([Permission::Shell]),
        );
        assert!(
            edit.render().contains("# waiting on 2.0"),
            "{}",
            edit.render()
        );
    }

    #[test]
    fn edits_keep_comments_and_formatting() {
        let text = "# mine\nformat = 1\nclients = [\"claude-code\"]  # keep\n\n[assets]\n# pinned\nold = \"^1\"\n";
        let mut edit = ConfigEdit::parse(text).unwrap();
        let id = AssetId::new("new-one").unwrap();
        assert!(edit.add_asset(&id, "^2.0.0"));
        assert!(!edit.add_asset(&id, "^2.0.0"));
        edit.set_inline_allow(&id, &BTreeSet::from([Permission::Shell]));
        assert!(edit.add_to_array("bundles", "rust-cli"));
        edit.set_allow(
            &AssetId::new("member").unwrap(),
            &BTreeSet::from([Permission::Hooks]),
        );
        let rendered = edit.render();
        assert!(
            rendered.contains("# mine")
                && rendered.contains("# keep")
                && rendered.contains("# pinned")
        );
        let config = ProjectConfig::from_toml(&rendered).unwrap();
        assert_eq!(config.bundles.len(), 1);
        assert_eq!(config.allowed(&id), BTreeSet::from([Permission::Shell]));
        assert_eq!(config.assets[&id].version().to_string(), "^2.0.0");

        let mut edit = ConfigEdit::parse(&rendered).unwrap();
        assert!(edit.remove_asset(&id));
        assert!(edit.remove_allow(&AssetId::new("member").unwrap()));
        assert!(edit.remove_from_array("bundles", "rust-cli"));
        let config = ProjectConfig::from_toml(&edit.render()).unwrap();
        assert!(config.allow.is_empty() && config.bundles.is_empty());
        assert!(edit.render().contains("# pinned"));
    }
}
