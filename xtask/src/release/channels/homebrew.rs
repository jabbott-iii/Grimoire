//! Homebrew: a prebuilt-binary formula for `jabbott-iii/homebrew-tap` (BREW and the
//! brew-scoop Phase 5 research in docs/specs.md, ADR-0009). The tap's sync workflow
//! copies this file from each attested release; nothing bumps it in place.
//!
//! The four archives sit in nested `on_macos`/`on_linux` > `on_arm`/`on_intel` blocks;
//! `brew style` checks only direct children of a top-level `on_*` block, and the
//! version comes from the `/releases/download/vX.Y.Z/` URL, so it isn't repeated.

use std::fmt::Write as _;

use super::{Input, SHORT_DESCRIPTION};
use crate::release::targets::{self, BIN, PACKAGE, REPO_URL};

/// `on_macos`/`on_linux` blocks, each with its `on_arm` and `on_intel` archive.
const LAYOUT: [(&str, [(&str, &str); 2]); 2] = [
    (
        "on_macos",
        [
            ("on_arm", "aarch64-apple-darwin"),
            ("on_intel", "x86_64-apple-darwin"),
        ],
    ),
    (
        "on_linux",
        [
            ("on_arm", "aarch64-unknown-linux-musl"),
            ("on_intel", "x86_64-unknown-linux-musl"),
        ],
    ),
];

pub(super) fn formula(input: &Input) -> String {
    let mut f = String::new();
    let _ = writeln!(
        f,
        "# Generated by `cargo xtask release channels` for {PACKAGE} {}.",
        input.version
    );
    let _ = writeln!(
        f,
        "# Do not edit: the tap's sync workflow replaces it from each release."
    );
    f.push_str("class AgentGrimoire < Formula\n");
    let _ = writeln!(f, "  desc \"{SHORT_DESCRIPTION}\"");
    let _ = writeln!(f, "  homepage \"{REPO_URL}\"");
    f.push_str("  license any_of: [\"MIT\", \"Apache-2.0\"]\n\n");
    f.push_str("  livecheck do\n    url :stable\n    strategy :github_latest\n  end\n");
    for (os, arches) in LAYOUT {
        let _ = writeln!(f, "\n  {os} do");
        for (i, (arch, triple)) in arches.iter().enumerate() {
            let target = targets::find(triple).unwrap_or(&targets::TARGETS[0]);
            let archive = target.archive(PACKAGE, &input.version);
            if i > 0 {
                f.push('\n');
            }
            let _ = writeln!(f, "    {arch} do");
            let _ = writeln!(
                f,
                "      url \"{}\"",
                targets::download_url(&input.version, &archive)
            );
            let _ = writeln!(f, "      sha256 \"{}\"", input.sha256(triple));
            f.push_str("    end\n");
        }
        f.push_str("  end\n");
    }
    let _ = writeln!(f, "\n  def install\n    bin.install \"{BIN}\"\n  end");
    let _ = writeln!(
        f,
        "\n  test do\n    assert_match \"{BIN} #{{version}}\", shell_output(\"#{{bin}}/{BIN} --version\")\n  end"
    );
    f.push_str("end\n");
    f
}

#[cfg(test)]
mod tests {
    use super::super::tests::input;
    use super::*;

    #[test]
    fn formula() {
        insta::assert_snapshot!(super::formula(&input(false)));
        assert!(SHORT_DESCRIPTION.len() <= 80);
        for (_, arches) in LAYOUT {
            for (_, triple) in arches {
                assert!(targets::find(triple).is_ok());
            }
        }
    }
}
